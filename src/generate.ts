			files: ["dist", "README.md", "SKILL.md"],
			scripts: {
				build: "tsc -p tsconfig.build.json",
				check: "tsc -p tsconfig.json",
				test: "vitest --run --passWithNoTests",
			},
			dependencies,
			peerDependencies: { effect: `~${TOOLCHAIN.effect}` },
